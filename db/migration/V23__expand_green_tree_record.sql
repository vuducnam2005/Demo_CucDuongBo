-- Expand phase: introduce the dedicated green-tree table without changing legacy data.
CREATE TABLE green_tree_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    raw_record_id BIGINT REFERENCES raw_dataset_record(id) ON DELETE SET NULL,
    record_id VARCHAR(150) NOT NULL UNIQUE,
    gid BIGINT,

    name VARCHAR(500) NOT NULL,
    tree_code VARCHAR(150),
    species_name VARCHAR(255),
    scientific_name VARCHAR(255),

    route_code VARCHAR(100),
    route_name VARCHAR(255),
    km_from NUMERIC(10, 3),
    km_to NUMERIC(10, 3),
    lytrinh VARCHAR(100),

    province_id VARCHAR(100),
    province_name VARCHAR(150),
    district_name VARCHAR(150),
    town_name VARCHAR(150),
    road_class VARCHAR(100),
    road_type VARCHAR(100),

    organization_id VARCHAR(100) DEFAULT 'moc_dbvn',
    branch_id VARCHAR(100),
    branch_name VARCHAR(255),
    management_agency VARCHAR(255),

    state VARCHAR(50) DEFAULT 'Approved',
    state_name VARCHAR(100) DEFAULT 'Đã duyệt',
    level_state VARCHAR(50) DEFAULT 'cdb_vn',
    active_status VARCHAR(100),
    maintain_value NUMERIC(18, 2) DEFAULT 0,
    construction_year INTEGER,
    parent_id VARCHAR(150),

    diameter_cm NUMERIC,
    height_m NUMERIC,
    canopy_diameter_m NUMERIC,
    planting_year INTEGER,
    health_status VARCHAR(255),
    risk_level VARCHAR(100),
    notes TEXT,

    geom GEOMETRY(Point, 4326),
    attributes JSONB NOT NULL DEFAULT '{}'::jsonb,

    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP WITH TIME ZONE,
    deleted_by VARCHAR(100),
    version INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_green_tree_attributes_object
        CHECK (jsonb_typeof(attributes) = 'object'),
    CONSTRAINT chk_green_tree_diameter_non_negative
        CHECK (diameter_cm IS NULL OR diameter_cm >= 0),
    CONSTRAINT chk_green_tree_height_non_negative
        CHECK (height_m IS NULL OR height_m >= 0),
    CONSTRAINT chk_green_tree_canopy_non_negative
        CHECK (canopy_diameter_m IS NULL OR canopy_diameter_m >= 0)
);

CREATE INDEX idx_green_tree_raw_record ON green_tree_record(raw_record_id);
CREATE INDEX idx_green_tree_branch_deleted ON green_tree_record(branch_id, is_deleted);
CREATE INDEX idx_green_tree_route_deleted ON green_tree_record(route_code, is_deleted);
CREATE INDEX idx_green_tree_province_deleted ON green_tree_record(province_id, is_deleted);
CREATE INDEX idx_green_tree_state_deleted ON green_tree_record(state, is_deleted);
CREATE INDEX idx_green_tree_species ON green_tree_record(species_name);
CREATE INDEX idx_green_tree_health ON green_tree_record(health_status);
CREATE INDEX idx_green_tree_risk ON green_tree_record(risk_level);
CREATE INDEX idx_green_tree_geom_gist ON green_tree_record USING GIST (geom);
CREATE INDEX idx_green_tree_attributes_gin
    ON green_tree_record USING GIN (attributes jsonb_path_ops);

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_trgm') THEN
        EXECUTE 'CREATE INDEX idx_green_tree_name_trgm ON green_tree_record USING GIN (name gin_trgm_ops)';
    END IF;
END;
$$;

COMMENT ON TABLE green_tree_record IS
    'Dedicated operational storage for dataset green_trees. Legacy asset_record remains intact until an approved contract release.';
COMMENT ON COLUMN green_tree_record.raw_record_id IS
    'Optional immutable lineage link. No unique constraint is added until production preflight proves one-to-one lineage.';

